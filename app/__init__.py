# ==============================================================================
# app/__init__.py - Python Package Identifier
# ==============================================================================
# In Python, an '__init__.py' file tells the Python interpreter that the directory
# it lives in ('app') should be treated as a Python package.
#
# This allows files in other parts of the project to import code from this folder,
# for example:
#     from app.models import ExpenseCreate
#     from app.services import get_all_expenses
#
# Even though this file is often left blank, its presence is what makes
# package-level imports work cleanly and reliably across Python versions.
